class Teacher(Employee):
    counter = 0

    def __init__(self, name, age, gender, address, salary, subjects=None):
        super().__init__(name, age, gender, address, salary)
        Teacher.counter += 1
        self.__teacher_id = f"TEC{Teacher.counter:02d}"
        self.subjects = subjects if subjects else []
    def __del__(self):
        Teacher.counter -= 1

    @property
    def teacher_id(self):
        return self.__teacher_id

    @property
    def get_counter(cls):
        return cls.counter

    def add_subject(self, subject):
        if subject not in self.subjects:
            self.subjects.append(subject)

    def remove_subject(self, subject):
        if subject in self.subjects:
            self.subjects.remove(subject)

    def introduce(self):
        return f"Hi, I'm {self.name}, a teacher with ID {self.teacher_id}. I teach: {', '.join(self.subjects) if self.subjects else 'No subjects assigned yet.'}"

    @property
    def employee_id(self):
        raise AttributeError("Teacher object has no attribute 'employee_id'")

