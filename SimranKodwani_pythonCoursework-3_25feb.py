from abc import ABC, abstractmethod
class Person:
    def __init__(self, name, age, gender, address):
        self.name = name
        self.age = age
        self.gender = gender
        self.address = address

    def __str__(self):
      return (f"Name: {self.name}, Age: {self.age}, Gender: {self.gender}, Address: {self.address}")

    def greet(self):
        print(f"Hello {self.name} My name is Jane ")


    @abstractmethod
    def introduce(self):
      pass

    @staticmethod
    def is_adult(age):
      if age > 18:
        return True
      else:
        return False

class child(Person):
    def __init__(self, name, age, gender, address,student_id):
      super().__init__(name, age, gender, address)
      self.student_id = student_id

    def introduce(self):
        return f"Hi, I'm {self.name}, a student with ID {self.student_id}."

